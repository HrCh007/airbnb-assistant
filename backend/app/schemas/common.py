"""Schemas for documents, curated recommendations, places, chat and admin."""

from __future__ import annotations

import uuid
from datetime import datetime
from enum import StrEnum
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field


# --------------------------------------------------------------------------- documents
class DocumentOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)
    id: uuid.UUID
    property_id: uuid.UUID
    property_name: str | None = None
    filename: str
    document_type: str
    size_bytes: int
    status: str
    error_message: str | None = None
    chunk_count: int
    is_system: bool
    uploaded_at: datetime
    last_indexed_at: datetime | None = None


# --------------------------------------------------------------------------- curated
class CuratedIn(BaseModel):
    property_id: uuid.UUID
    name: str = Field(min_length=2, max_length=200)
    category: str = Field(min_length=2, max_length=60)
    note: str | None = Field(default=None, max_length=1000)
    address: str | None = Field(default=None, max_length=500)
    latitude: float | None = Field(default=None, ge=-90, le=90)
    longitude: float | None = Field(default=None, ge=-180, le=180)
    google_place_id: str | None = Field(default=None, max_length=255)
    tags: list[str] = Field(default_factory=list, max_length=20)
    is_active: bool = True


class CuratedOut(CuratedIn):
    model_config = ConfigDict(from_attributes=True)
    id: uuid.UUID
    created_at: datetime


# --------------------------------------------------------------------------- places
class PlaceResult(BaseModel):
    """A local recommendation. Every field comes from Google Places or the host's
    curated list - never generated by the LLM."""

    place_id: str | None = None
    name: str
    category: str | None = None
    types: list[str] = []
    address: str | None = None
    latitude: float | None = None
    longitude: float | None = None
    distance_km: float | None = None
    rating: float | None = None
    user_rating_count: int | None = None
    price_level: int | None = None  # 0 free .. 4 very expensive
    open_now: bool | None = None
    opening_hours: list[str] = []
    phone: str | None = None
    website: str | None = None
    summary: str | None = None
    maps_url: str | None = None
    directions_url: str | None = None
    source: Literal["google_places", "host_curated", "mock"] = "google_places"
    host_note: str | None = None
    score: float | None = None


class PlacesSearchRequest(BaseModel):
    property_id: uuid.UUID
    query: str = Field(min_length=2, max_length=200)
    included_type: str | None = Field(default=None, max_length=60)
    radius_m: int | None = Field(default=None, ge=100, le=50000)
    open_now: bool | None = None
    max_price_level: int | None = Field(default=None, ge=0, le=4)
    min_rating: float | None = Field(default=None, ge=0, le=5)
    limit: int = Field(default=5, ge=1, le=10)


class PlacesSearchResponse(BaseModel):
    provider: str
    origin: dict
    radius_m: int
    results: list[PlaceResult]
    notice: str | None = None


# --------------------------------------------------------------------------- chat
class Intent(StrEnum):
    PROPERTY_QUERY = "PROPERTY_QUERY"
    LOCAL_DISCOVERY_QUERY = "LOCAL_DISCOVERY_QUERY"
    GENERAL_NEIGHBOURHOOD_QUERY = "GENERAL_NEIGHBOURHOOD_QUERY"
    MIXED_QUERY = "MIXED_QUERY"
    GENERAL_CONVERSATION = "GENERAL_CONVERSATION"
    EMERGENCY_QUERY = "EMERGENCY_QUERY"


class SessionCreate(BaseModel):
    location_slug: str | None = None
    property_id: uuid.UUID | None = None


class SessionSelect(BaseModel):
    location_slug: str | None = None
    property_id: uuid.UUID | None = None


class SessionOut(BaseModel):
    session_id: uuid.UUID
    session_token: str | None = None  # only returned once, on creation
    location_slug: str | None = None
    location_name: str | None = None
    property: dict | None = None
    available_properties: list[dict] = []
    preferences: dict = {}
    pin_verified: bool = False
    created_at: datetime


class ChatMessageIn(BaseModel):
    session_id: uuid.UUID
    message: str = Field(min_length=1, max_length=1500)


class PinVerifyIn(BaseModel):
    pin: str = Field(min_length=4, max_length=12)


class MessageOut(BaseModel):
    id: uuid.UUID
    role: str
    content: str
    intent: str | None = None
    places: list[PlaceResult] = []
    suggestions: list[str] = []
    created_at: datetime


# --------------------------------------------------------------------------- admin
class LoginIn(BaseModel):
    email: str = Field(min_length=3, max_length=255)
    password: str = Field(min_length=1, max_length=200)


class TokenOut(BaseModel):
    access_token: str
    token_type: str = "bearer"
    expires_at: datetime
